import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const migrationDirectory = new URL("db/migrations/", root);
const output = new URL("db/generated-migrations.ts", root);
const wranglerOutput = new URL("db/wrangler/", root);
const manifestOutput = new URL("db/migrations-manifest.json", root);
const names = (await readdir(migrationDirectory)).filter((name) => /^\d{4}_[a-z0-9_]+\.sql$/.test(name)).sort();
const migrations = [];
const toWranglerStatement = (statement) => /^CREATE TRIGGER\b/i.test(statement)
  ? statement.replace(/SELECT CASE ([^;]+) END;/g, "SELECT (CASE $1 END);")
  : statement;

for (const [index, filename] of names.entries()) {
  const version = Number(filename.slice(0, 4));
  if (version !== index + 1) throw new Error(`Migration sequence gap at ${filename}`);
  const sql = (await readFile(new URL(filename, migrationDirectory), "utf8")).replace(/\r\n/g, "\n").trim();
  const destructive = /^-- migration-destructive: true$/m.test(sql);
  const requiresProjectExport = /^-- migration-requires-project-export: true$/m.test(sql);
  const executableSql = sql.replace(/^-- migration-(?:destructive|requires-project-export): (?:true|false)\n/gm, "").trim();
  const statements = executableSql.split(/^-- statement-breakpoint$/m).map((statement) => statement.trim()).filter(Boolean);
  if (!statements.length || statements.some((statement) => statement.includes(";") && !/^CREATE TRIGGER[\s\S]+\bBEGIN[\s\S]+\bEND$/i.test(statement))) throw new Error(`${filename} must contain one SQL statement per block`);
  migrations.push({ version, name: filename.slice(5, -4), checksum: createHash("sha256").update(`${sql}\n`).digest("hex"), destructive, requiresProjectExport, statements });
}

const source = `// Generated by scripts/generate-db-migrations.mjs. Do not edit.\nexport const DATABASE_MIGRATIONS = Object.freeze(${JSON.stringify(migrations, null, 2)});\nexport const DATABASE_SCHEMA_VERSION = ${migrations.length};\n`;
await mkdir(new URL("./", output), { recursive: true });
await writeFile(output, source);
await mkdir(wranglerOutput, { recursive: true });
for (const migration of migrations) {
  const filename = `${String(migration.version).padStart(4, "0")}_${migration.name}.sql`;
  const appliedAt = "CURRENT_TIMESTAMP";
  const sql = [
    "CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, name TEXT NOT NULL, checksum TEXT NOT NULL, applied_at TEXT NOT NULL, adopted INTEGER NOT NULL DEFAULT 0);",
    ...migration.statements.map((statement) => `${toWranglerStatement(statement)};`),
    `INSERT INTO schema_migrations (version, name, checksum, applied_at, adopted) VALUES (${migration.version}, '${migration.name}', '${migration.checksum}', ${appliedAt}, 0);`,
    "",
  ].join("\n");
  await writeFile(new URL(filename, wranglerOutput), sql);
}
await writeFile(manifestOutput, `${JSON.stringify({ schemaVersion: 1, databaseSchemaVersion: migrations.length, migrations: migrations.map(({ statements, ...migration }) => ({ ...migration, source: `/db/migrations/${String(migration.version).padStart(4, "0")}_${migration.name}.sql`, wrangler: `/db/wrangler/${String(migration.version).padStart(4, "0")}_${migration.name}.sql`, statementCount: statements.length })) }, null, 2)}\n`);
console.log(`Generated ${migrations.length} numbered database migrations`);
